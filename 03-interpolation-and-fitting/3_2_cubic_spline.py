import numpy as np

# 1. ИСХОДНЫЕ ДАННЫЕ (Вариант 17)
x = np.array([-2.0, -1.0, 0.0, 1.0, 2.0])
f = np.array([-1.8647, -0.63212, 1.0, 3.7183, 9.3891])
X_star = -0.5

n = len(x) - 1  # Количество интервалов (n = 4)
h = np.diff(x)  # Шаги сетки h_i = x_i - x_{i-1}

# 2. ПОСТРОЕНИЕ СЛАУ ДЛЯ КОЭФФИЦИЕНТОВ c (Формула 3.13)
# Размерность матрицы (n-1)x(n-1), т.к. граничные c_1 и c_n равны 0
A = np.zeros((n - 1, n - 1))
B = np.zeros(n - 1)

for i in range(1, n):
    idx = i - 1  # Индекс строки в матрице Python

    # Правая часть уравнений системы (разделенные разности)
    B[idx] = 3 * ((f[i + 1] - f[i]) / h[i] - (f[i] - f[i - 1]) / h[i - 1])

    # Главная диагональ матрицы (коэффициент при текущем c_i)
    A[idx, idx] = 2 * (h[i - 1] + h[i])

    # Внедиагональные элементы (коэффициенты при c_{i-1} и c_{i+1})
    if idx > 0:
        A[idx, idx - 1] = h[i - 1]
    if idx < n - 2:
        A[idx, idx + 1] = h[i]

# Решаем систему и находим внутренние коэффициенты c
c_internal = np.linalg.solve(A, B)

# Собираем полный вектор c, учитывая условия нулевой кривизны на краях: c[0]=0, c[n]=0
c = np.zeros(n + 1)
c[1:n] = c_internal

# 3. ВЫЧИСЛЕНИЕ КОЭФФИЦИЕНТОВ a, b, d (Формулы 3.14)
a = np.zeros(n)
b = np.zeros(n)
d = np.zeros(n)

for i in range(n):
    a[i] = f[i]  # Коэффициент a_i равен значению в левом узле

    if i < n - 1:
        # Стандартные формулы для интервалов с 1 по n-1
        b[i] = (f[i + 1] - f[i]) / h[i] - (1 / 3) * h[i] * (c[i + 2] + 2 * c[i + 1])
        d[i] = (c[i + 2] - c[i + 1]) / (3 * h[i])
    else:
        # Особые формулы для последнего интервала (n)
        b[i] = (f[i + 1] - f[i]) / h[i] - (2 / 3) * h[i] * c[i + 1]
        d[i] = -c[i + 1] / (3 * h[i])

# Вывод таблицы полученных коэффициентов
print(f"{'Интервал':<10}{'a_i':<12}{'b_i':<12}{'c_i (S_i'')':<14}{'d_i':<12}")
for i in range(n):
    print(f"{i + 1:<10}{a[i]:<12.5f}{b[i]:<12.5f}{c[i + 1]:<14.5f}{d[i]:<12.5f}")

# 4. ВЫЧИСЛЕНИЕ ЗНАЧЕНИЯ В ТОЧКЕ X*
# Поиск интервала, в который попадает заданная точка X*
interval_idx = -1
for i in range(n):
    if x[i] <= X_star <= x[i + 1]:
        interval_idx = i
        break

if interval_idx != -1:
    # dx = (x - x_{i-1}) — локальное смещение от левой границы интервала
    dx = X_star - x[interval_idx]

    # Считаем значение кубического сплайна на выбранном интервале
    S_X = (a[interval_idx] +
           b[interval_idx] * dx +
           (c[interval_idx + 1] / 2) * (dx ** 2) +
           (d[interval_idx] / 6) * (dx ** 3))

    print(f"\nТочка X* = {X_star} принадлежит интервалу №{interval_idx + 1} [{x[interval_idx]}; {x[interval_idx + 1]}]")
    print(f"Значение функции в точке X*: S(X*) = {S_X:.6f}")
else:
    print("\nОшибка: Точка X* находится вне диапазона интерполяции!")